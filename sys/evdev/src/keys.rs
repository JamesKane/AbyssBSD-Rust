/// The evdev code for HID keyboard usage `usage` (`evdev_hid2key`), or
/// `KEY_RESERVED` (0) if it has none.
#[must_use]
pub fn hid2key(usage: u8) -> u16 {
    HID_TO_KEY[usize::from(usage)]
}

