//! Renders parsed entries as the Rust tables in `lib/abi/src/syscall/`.

use std::collections::HashMap;
use std::fmt::{self, Write};

use crate::parse::{CompatLevel, Decl, Entry, Kind};

/// Why the tables could not be rendered.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum RenderError {
    /// Two live syscalls map to the same Rust variant name.
    DuplicateVariant {
        variant: String,
        first: u32,
        second: u32,
    },
}

impl fmt::Display for RenderError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::DuplicateVariant {
                variant,
                first,
                second,
            } => write!(
                f,
                "syscalls {first} and {second} both map to variant `{variant}`"
            ),
        }
    }
}

impl std::error::Error for RenderError {}

/// Names that would collide after the general rule, mapped by hand.
/// `__syscall` is BSD's "quad" indirect syscall (64-bit number argument).
const RENAMES: &[(&str, &str)] = &[("__syscall", "SyscallQuad")];

/// Converts a C syscall name to a Rust variant: leading underscores are
/// dropped and `snake_case` becomes `CamelCase` (`__sysctlbyname` →
/// `Sysctlbyname`, `_umtx_op` → `UmtxOp`), except for [`RENAMES`].
pub(crate) fn variant_name(c_name: &str) -> String {
    if let Some((_, v)) = RENAMES.iter().find(|(c, _)| *c == c_name) {
        return (*v).to_owned();
    }
    c_name
        .split('_')
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut cs = p.chars();
            cs.next()
                .map(|c| c.to_ascii_uppercase().to_string() + cs.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn prototype(d: &Decl) -> String {
    let mut args: Vec<String> = d
        .args
        .iter()
        .map(|a| format!("{} {}", a.ty, a.name))
        .collect();
    if d.variadic {
        args.push("...".into());
    }
    let args = if args.is_empty() {
        "void".to_owned()
    } else {
        args.join(", ")
    };
    format!("{} {}({})", d.ret, d.name, args).replace("* ", "*")
}

fn compat_level(level: CompatLevel) -> String {
    match level {
        CompatLevel::Bsd43 => "CompatLevel::Bsd43".into(),
        CompatLevel::FreeBsd(n) => format!("CompatLevel::FreeBsd({n})"),
    }
}

/// Renders the generated module. `provenance` names the input (path and
/// revision) for the header comment.
pub fn render(entries: &[Entry], provenance: &str) -> Result<String, RenderError> {
    let live: Vec<(&Entry, &Decl, String)> = entries
        .iter()
        .filter(|e| e.kind.is_live())
        .filter_map(|e| e.decl.as_ref().map(|d| (e, d, variant_name(&d.name))))
        .collect();

    let mut seen: HashMap<&str, u32> = HashMap::new();
    for (e, _, v) in &live {
        if let Some(&first) = seen.get(v.as_str()) {
            return Err(RenderError::DuplicateVariant {
                variant: v.clone(),
                first,
                second: e.number,
            });
        }
        seen.insert(v, e.number);
    }

    let mut o = String::new();
    // `String` as a `fmt::Write` sink cannot fail.
    let w = &mut o;
    let _ = render_into(w, entries, &live, provenance);
    Ok(o)
}

fn render_into(
    o: &mut String,
    entries: &[Entry],
    live: &[(&Entry, &Decl, String)],
    provenance: &str,
) -> fmt::Result {
    writeln!(o, "// SPDX-License-Identifier: BSD-2-Clause")?;
    writeln!(
        o,
        "// @generated by `cargo xtask syscallgen` from {provenance}."
    )?;
    writeln!(o, "// Do not edit by hand.")?;
    writeln!(o)?;
    writeln!(o, "use super::{{ArgInfo, CompatLevel, Slot, SyscallInfo}};")?;
    writeln!(o)?;

    writeln!(o, "/// Number of slots in the FreeBSD syscall table.")?;
    writeln!(o, "pub const SLOT_COUNT: usize = {};", entries.len())?;
    writeln!(o)?;
    writeln!(o, "/// Number of live syscalls.")?;
    writeln!(o, "pub const LIVE_COUNT: usize = {};", live.len())?;
    writeln!(o)?;

    writeln!(
        o,
        "/// A live FreeBSD syscall. The discriminant is the syscall number."
    )?;
    writeln!(
        o,
        "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]"
    )?;
    writeln!(o, "#[repr(u32)]")?;
    writeln!(o, "pub enum Sysno {{")?;
    for (e, d, v) in live {
        writeln!(o, "    /// `{}`", prototype(d))?;
        writeln!(o, "    {v} = {},", e.number)?;
    }
    writeln!(o, "}}")?;
    writeln!(o)?;

    writeln!(o, "impl Sysno {{")?;
    writeln!(o, "    /// Every live syscall, in number order.")?;
    writeln!(o, "    pub const ALL: [Self; LIVE_COUNT] = [")?;
    for (_, _, v) in live {
        writeln!(o, "        Self::{v},")?;
    }
    writeln!(o, "    ];")?;
    writeln!(o)?;
    writeln!(o, "    /// Position in [`Sysno::ALL`] and [`SYSCALLS`].")?;
    writeln!(o, "    pub const fn index(self) -> usize {{")?;
    writeln!(o, "        match self {{")?;
    for (i, (_, _, v)) in live.iter().enumerate() {
        writeln!(o, "            Self::{v} => {i},")?;
    }
    writeln!(o, "        }}")?;
    writeln!(o, "    }}")?;
    writeln!(o, "}}")?;
    writeln!(o)?;

    writeln!(o, "/// Every slot of the syscall table, indexed by number.")?;
    writeln!(o, "pub static SLOTS: [Slot; SLOT_COUNT] = [")?;
    for e in entries {
        let name = e
            .decl
            .as_ref()
            .map(|d| d.name.clone())
            .or_else(|| e.comment.clone())
            .unwrap_or_default();
        let slot = match e.kind {
            Kind::Std | Kind::NoStd | Kind::NoDef | Kind::SysMux => {
                let d = e
                    .decl
                    .as_ref()
                    .map(|d| variant_name(&d.name))
                    .unwrap_or_default();
                format!("Slot::Live(Sysno::{d})")
            }
            Kind::Compat(level) => {
                format!(
                    "Slot::Compat {{ level: {}, name: {name:?} }}",
                    compat_level(level)
                )
            }
            Kind::Obsolete => format!("Slot::Obsolete({name:?})"),
            Kind::Reserved => "Slot::Reserved".into(),
            Kind::Unimplemented => "Slot::Unimplemented".into(),
            Kind::ModuleSlot => "Slot::Module".into(),
        };
        writeln!(o, "    {slot}, // {}", e.number)?;
    }
    writeln!(o, "];")?;
    writeln!(o)?;

    writeln!(
        o,
        "/// Descriptions of the live syscalls, in [`Sysno::ALL`] order."
    )?;
    writeln!(o, "pub static SYSCALLS: [SyscallInfo; LIVE_COUNT] = [")?;
    for (e, d, v) in live {
        writeln!(o, "    SyscallInfo {{")?;
        writeln!(o, "        sysno: Sysno::{v},")?;
        writeln!(o, "        name: {:?},", d.name)?;
        writeln!(o, "        ret: {:?},", d.ret)?;
        writeln!(o, "        args: &[")?;
        for a in &d.args {
            writeln!(
                o,
                "            ArgInfo {{ ty: {:?}, name: {:?}, annotations: {:?} }},",
                a.ty, a.name, a.annotations
            )?;
        }
        writeln!(o, "        ],")?;
        writeln!(o, "        variadic: {},", d.variadic)?;
        writeln!(o, "        cap_enabled: {},", e.flags.cap_enabled)?;
        writeln!(o, "        no_return: {},", e.flags.no_return)?;
        writeln!(
            o,
            "        loadable: {},",
            e.kind == Kind::NoStd || e.flags.not_static
        )?;
        writeln!(o, "    }},")?;
    }
    writeln!(o, "];")?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parse::parse;

    #[test]
    fn variant_names() {
        assert_eq!(variant_name("__sysctlbyname"), "Sysctlbyname");
        assert_eq!(variant_name("_umtx_op"), "UmtxOp");
        assert_eq!(variant_name("_exit"), "Exit");
        assert_eq!(variant_name("read"), "Read");
        assert_eq!(variant_name("__syscall"), "SyscallQuad");
    }

    #[test]
    fn renders_slots_and_info() {
        let src = "0\tAUE_NULL\tSTD {\n int fork(void);\n }\n1\tAUE_NULL\tOBSOL\tvread\n\
                   2\tAUE_READ\tSTD|CAPENABLED {\n ssize_t read(int fd, _Out_ void *buf);\n }\n";
        let out = render(&parse(src).unwrap(), "test").unwrap();
        assert!(out.contains("pub const SLOT_COUNT: usize = 3;"));
        assert!(out.contains("    /// `ssize_t read(int fd, void *buf)`\n    Read = 2,"));
        assert!(out.contains("Slot::Obsolete(\"vread\"), // 1"));
        assert!(out.contains("cap_enabled: true,"));
    }

    #[test]
    fn duplicate_variants_fail() {
        let src =
            "0\tAUE_NULL\tSTD {\n int __foo(void);\n }\n1\tAUE_NULL\tSTD {\n int foo(void);\n }\n";
        assert!(matches!(
            render(&parse(src).unwrap(), "t"),
            Err(RenderError::DuplicateVariant {
                first: 0,
                second: 1,
                ..
            })
        ));
    }
}
