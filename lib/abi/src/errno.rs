//! Error numbers, with FreeBSD's values (`sys/errno.h`).
//!
//! System calls return them with the carry flag set (amd64 `CF`, arm64
//! `PSTATE.C`). `cargo xtask abi-check` checks every value against
//! FreeBSD's headers.

